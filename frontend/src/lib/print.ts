export interface ReadingReportData {
  manuscriptTitle: string;
  manuscriptNumber: string;
  readerName: string;
  submittedAt: string;
  recommendation: string;
  globalScore: number;
  overallComment: string | null;
  scores: { label: string; coefficient: number; score: number; comment: string | null }[];
}

// Rapport de lecture d'un relecteur : reprend l'évaluation remise (critères
// notés, score global, recommandation, appréciation) en document imprimable/PDF.
export function printReadingReport(d: ReadingReportData, opts?: PrintOpts): void {
  const rows = d.scores
    .map(
      (s) =>
        `<tr><td>${escapeHtml(s.label)}</td><td class="r num">${s.coefficient}</td><td class="r num">${s.score} / 10</td><td>${escapeHtml(s.comment ?? "")}</td></tr>`,
    )
    .join("");

  const body = `
    <div class="doc__title">${tr("Rapport de lecture", "Reading report")}</div>
    <div class="meta">
      <span>${tr("Manuscrit", "Manuscript")} : <b class="num">${escapeHtml(d.manuscriptNumber)}</b></span>
      <span>${tr("Remis le", "Submitted on")} <b class="num">${fdate(d.submittedAt)}</b></span>
    </div>
    <div class="party">
      <div class="party__label">${tr("Ouvrage", "Title")}</div>
      <div class="party__name">${escapeHtml(d.manuscriptTitle)}</div>
    </div>
    <div class="party" style="margin-top:10px">
      <div class="party__label">${tr("Relecteur", "Reviewer")}</div>
      <div class="party__name">${escapeHtml(d.readerName)}</div>
    </div>
    <table class="lines" style="margin-top:16px"><thead><tr><th>${tr("Critère", "Criterion")}</th><th class="r">${tr("Coef.", "Weight")}</th><th class="r">${tr("Note", "Score")}</th><th>${tr("Commentaire", "Comment")}</th></tr></thead><tbody>
      ${rows}
      <tr><td colspan="2"><b>${tr("Score global", "Overall score")}</b></td><td class="r num"><b>${d.globalScore} / 10</b></td><td></td></tr>
    </tbody></table>
    <div class="party" style="margin-top:16px">
      <div class="party__label">${tr("Recommandation", "Recommendation")}</div>
      <div class="party__name">${escapeHtml(label(READING_RECO_LABELS, d.recommendation))}</div>
    </div>
    ${
      d.overallComment
        ? `<div style="margin-top:14px"><div class="party__label">${tr("Appréciation générale", "General assessment")}</div><div style="font-size:12.5px;color:#1f2937;white-space:pre-wrap;margin-top:4px">${escapeHtml(d.overallComment)}</div></div>`
        : ""
    }`;

  openPrintWindow(`${tr("Rapport de lecture", "Reading report")} — ${d.manuscriptTitle}`, body, opts);
}

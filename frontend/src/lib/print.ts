// Câble l'impression d'un document généré (iframe ou fenêtre). L'impression est
// déclenchée DEPUIS LA PAGE COURANTE (code fourni par l'application), et non par
// un script inline dans le document : la politique de sécurité de l'app
// (`script-src 'self'`, voir backend app.ts) bloque tout script/handler inline —
// l'ancienne méthode (script inline `window.print()`) ne s'exécutait donc jamais
// et rien ne s'imprimait. Appeler `print()` depuis le parent est conforme à la
// CSP et fiable sur ordinateur comme sur mobile.
// Attend que TOUTES les images du document (logo, filigrane) soient chargées
// avant d'appeler la callback — avec un filet de sécurité si une image ne se
// charge jamais. Sans cela, sur une connexion modeste, l'impression automatique
// partait avant le chargement du logo → document imprimé/PDF SANS logo.
function whenImagesReady(doc: Document, cb: () => void, maxWait = 8000): void {
  const pending = Array.from(doc.images || []).filter((im) => !im.complete);
  if (pending.length === 0) { cb(); return; }
  let remaining = pending.length;
  let fired = false;
  const done = () => { if (!fired) { fired = true; cb(); } };
  const one = () => { remaining -= 1; if (remaining <= 0) done(); };
  pending.forEach((im) => { im.addEventListener("load", one); im.addEventListener("error", one); });
  setTimeout(done, maxWait);
}

function wirePrint(win: Window, doc: Document, autoPrint = true): void {
  let printed = false;
  const fire = () => {
    if (printed) return;
    printed = true;
    try {
      win.focus();
      win.print();
    } catch {
      /* certains contextes refusent print() : le bouton manuel reste dispo */
    }
  };
  // Bouton « Imprimer / Enregistrer en PDF » du document : câblé ici
  // (addEventListener), l'attribut onclick inline étant lui aussi bloqué par la CSP.
  const btn = doc.querySelector("button[data-print]");
  btn?.addEventListener("click", () => {
    try {
      win.focus();
      win.print();
    } catch {
      /* ignore */
    }
  });
  // Bouton « Fermer » : referme la fenêtre/onglet du document pour revenir
  // facilement à l'application (utile sur ordinateur, où l'aperçu s'ouvre à part).
  doc.querySelector("button[data-close]")?.addEventListener("click", () => {
    try { win.close(); } catch { /* ignore */ }
  });
  // Impression automatique : à l'évènement load (une fois les images chargées)
  // et, filet de sécurité, après un court délai si load ne se déclenche pas
  // (variable selon les navigateurs après un document.write). Le verrou `printed`
  // évite d'ouvrir deux fois la boîte d'impression.
  // Aperçu à l'écran : on NE lance PAS l'impression automatiquement — la personne
  // consulte le document (défilable, plein écran) puis clique le bouton si elle
  // veut imprimer / enregistrer en PDF.
  if (!autoPrint) return;
  // On imprime une fois les images (logo + filigrane) réellement chargées, pour
  // qu'aucun document ne sorte sans logo sur une connexion lente.
  win.addEventListener("load", () => whenImagesReady(doc, fire));
  whenImagesReady(doc, fire);
}

// Impression via une IFRAME cachée : impression directe et silencieuse, idéale
// sur ORDINATEUR, et non bloquée par les bloqueurs de pop-up (utile quand
// l'impression suit une étape asynchrone, ex. « Établir la facture »).
function printViaIframe(html: string, autoPrint = true): boolean {
  try {
    const iframe = document.createElement("iframe");
    iframe.setAttribute("aria-hidden", "true");
    // IMPORTANT : l'iframe doit avoir une VRAIE taille de page (A4), pas 0×0.
    // Une iframe 0×0 n'a pas de fenêtre de mise en page : à l'impression, le
    // navigateur rastérise alors le document à la résolution de l'écran — TOUT
    // le texte sort flou. En lui donnant les dimensions A4 (hors écran, à
    // gauche), le rendu d'impression reste vectoriel et net.
    iframe.style.cssText = "position:fixed;left:-11000px;top:0;width:210mm;height:297mm;border:0;";
    document.body.appendChild(iframe);
    const win = iframe.contentWindow;
    const idoc = win?.document;
    if (!win || !idoc) throw new Error("iframe indisponible");
    idoc.open();
    idoc.write(html);
    idoc.close();
    wirePrint(win, idoc, autoPrint);
    const remove = () => {
      if (iframe.parentNode) iframe.parentNode.removeChild(iframe);
    };
    win.addEventListener("afterprint", () => setTimeout(remove, 500));
    setTimeout(remove, 120000);
    return true;
  } catch {
    return false;
  }
}

// Impression via un NOUVEL ONGLET : le document y est seul, donc il s'imprime
// CORRECTEMENT sur mobile — contrairement à l'iframe, qui sur Android Chrome
// imprime la page entière de l'application au lieu du document. Peut être bloqué
// par un bloqueur de pop-up si l'appel ne suit pas une action de l'utilisateur.
function printViaWindow(html: string, autoPrint = true): boolean {
  const w = window.open("", "_blank");
  if (!w) return false;
  w.document.open();
  w.document.write(html);
  w.document.close();
  wirePrint(w, w.document, autoPrint);
  // Referme l'onglet une fois l'impression terminée (au mieux : afterprint
  // n'est pas garanti sur tous les mobiles — l'utilisateur peut fermer l'onglet).
  try {
    w.addEventListener("afterprint", () => setTimeout(() => w.close(), 300));
  } catch {
    /* ignore */
  }
  return true;
}

// Aperçu à l'écran DANS l'application (superposition) : le document s'affiche
// par-dessus la page, dans un cadre défilable, avec une barre « Imprimer /
// Enregistrer en PDF » et surtout « ✕ Fermer ». On revient à l'application d'un
// clic (ou avec Échap), sans onglet séparé à retrouver ni fenêtre à fermer —
// c'était le point douloureux sur ordinateur. Fonctionne aussi sur mobile.
function previewInModal(title: string, html: string): boolean {
  try {
    const overlay = document.createElement("div");
    overlay.style.cssText = "position:fixed; inset:0; z-index:100000; background:rgba(11,11,12,.62); display:flex; flex-direction:column; padding:0;";

    const bar = document.createElement("div");
    bar.style.cssText = "display:flex; align-items:center; gap:10px; padding:10px 14px; background:#0b0b0c; color:#fff; flex-wrap:wrap;";
    const label = document.createElement("div");
    label.textContent = title;
    label.style.cssText = "font:600 13px system-ui,-apple-system,'Segoe UI',sans-serif; flex:1; min-width:120px; overflow:hidden; text-overflow:ellipsis; white-space:nowrap;";
    const printBtn = document.createElement("button");
    printBtn.type = "button";
    printBtn.textContent = tr("Imprimer / Enregistrer en PDF", "Print / Save as PDF");
    printBtn.style.cssText = "font:600 12.5px inherit; background:#d9b21a; color:#0b0b0c; border:none; border-radius:7px; padding:8px 14px; cursor:pointer;";
    const closeBtn = document.createElement("button");
    closeBtn.type = "button";
    closeBtn.textContent = tr("✕ Fermer", "✕ Close");
    closeBtn.style.cssText = "font:600 12.5px inherit; background:#fff; color:#0b0b0c; border:none; border-radius:7px; padding:8px 14px; cursor:pointer;";

    const frame = document.createElement("iframe");
    frame.setAttribute("title", title);
    frame.style.cssText = "flex:1; width:100%; border:0; background:#fff;";
    frame.srcdoc = html;

    const close = () => {
      window.removeEventListener("keydown", onKey);
      if (overlay.parentNode) overlay.parentNode.removeChild(overlay);
    };
    const onKey = (e: KeyboardEvent) => { if (e.key === "Escape") close(); };
    closeBtn.addEventListener("click", close);
    overlay.addEventListener("click", (e) => { if (e.target === overlay) close(); });
    window.addEventListener("keydown", onKey);
    const doPrint = () => { try { frame.contentWindow?.focus(); frame.contentWindow?.print(); } catch { /* ignore */ } };
    printBtn.addEventListener("click", doPrint);
    // Le bouton « Imprimer » DANS le document (data-print) doit aussi fonctionner.
    frame.addEventListener("load", () => {
      try {
        const idoc = frame.contentDocument;
        idoc?.querySelector("button[data-print]")?.addEventListener("click", doPrint);
        idoc?.querySelector("button[data-close]")?.addEventListener("click", close);
      } catch { /* ignore */ }
    });

    bar.append(label, printBtn, closeBtn);
    overlay.append(bar, frame);
    document.body.appendChild(overlay);
    return true;
  } catch {
    return false;
  }
}

function openPrintWindow(title: string, body: string, opts?: PrintOpts): void {
  const html = documentShell(title, body, opts);

  // Aperçu à l'écran : superposition DANS l'application (retour facile), avec
  // repli sur un onglet visible si la superposition échoue.
  if (opts?.preview) {
    if (previewInModal(title, html)) return;
    if (printViaWindow(html, false)) return;
    if (printViaIframe(html, false)) return;
    alert(tr("Autorisez les fenêtres pop-up pour afficher l'aperçu.", "Allow pop-up windows to show the preview."));
    return;
  }

  // Choix de la méthode selon l'appareil :
  //  • MOBILE : nouvel onglet d'abord (l'iframe imprime la page entière sur
  //    Android Chrome) ; repli sur l'iframe si le pop-up est bloqué.
  //  • ORDINATEUR : iframe d'abord (impression directe, sans onglet visible, et
  //    non bloquée après une étape asynchrone) ; repli sur un nouvel onglet.
  const isMobile = /Android|iPhone|iPad|iPod|Mobile/i.test(navigator.userAgent || "");
  const chain = isMobile ? [printViaWindow, printViaIframe] : [printViaIframe, printViaWindow];
  for (const method of chain) {
    if (method(html)) return;
  }
  // Aucune méthode n'a pu s'ouvrir (pop-up bloqué et iframe indisponible).
  alert(tr("Autorisez les fenêtres pop-up pour imprimer ce document.", "Allow pop-up windows to print this document."));
}


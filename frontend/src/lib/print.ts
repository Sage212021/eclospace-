export interface CommissionStatementData {
  agentName: string;
  periodLabel: string; // ex. « Mois — du 01/01/2026 au 25/07/2026 »
  ratePct: number; // taux en pourcentage, ex. 10
  books: { title: string; units: number; amount: number; commission: number }[];
  totals: { units: number; amount: number; commission: number };
}

// État de commission d'un commercial sur une période (demande opérateur : la
// maison peut payer les commissions par semaine ou par mois). Détail par
// ouvrage — exemplaires, montant vendu, commission — puis totaux. La commission
// est « due » (calculée par l'application) ; le versement effectif est constaté
// à part. Prêt à imprimer / enregistrer en PDF.
export function printCommissionStatement(d: CommissionStatementData, opts?: PrintOpts): void {
  const cur = "XAF";
  const rows = d.books
    .map(
      (b) => `<tr>
        <td>${escapeHtml(b.title)}</td>
        <td class="r num">${fnum(b.units)}</td>
        <td class="r num">${money(b.amount, cur)}</td>
        <td class="r num">${money(b.commission, cur)}</td>
      </tr>`,
    )
    .join("");

  const rateStr = `${d.ratePct.toLocaleString(locale(), { maximumFractionDigits: 2 })} %`;
  const body = `
    <div class="doc__title">${tr("État de commission", "Commission statement")}</div>
    <div class="meta">
      <span>${tr("Période", "Period")} : <b>${escapeHtml(d.periodLabel)}</b></span>
      <span>${tr("Taux appliqué", "Applied rate")} : <b class="num">${rateStr}</b></span>
      <span>${tr("Édité le", "Issued on")} <b class="num">${fdate(new Date())}</b></span>
    </div>
    <div class="party">
      <div class="party__label">${tr("Commercial", "Salesperson")}</div>
      <div class="party__name">${escapeHtml(d.agentName)}</div>
    </div>
    <table class="lines" style="margin-top:12px">
      <thead><tr><th>${tr("Ouvrage", "Title")}</th><th class="r">${tr("Exempl. vendus", "Units sold")}</th><th class="r">${tr("Montant vendu", "Amount sold")}</th><th class="r">${tr("Commission due", "Commission due")}</th></tr></thead>
      <tbody>${rows || `<tr><td colspan="4">${tr("Aucune vente sur la période.", "No sales in this period.")}</td></tr>`}</tbody>
    </table>
    <div class="totals">
      <div><span>${tr("Exemplaires vendus", "Units sold")}</span><span class="num">${fnum(d.totals.units)}</span></div>
      <div><span>${tr("Montant vendu", "Amount sold")}</span><span class="num">${money(d.totals.amount, cur)}</span></div>
      <div class="ttc"><span>${tr("Commission due", "Commission due")}</span><span class="num">${money(d.totals.commission, cur)}</span></div>
    </div>
    <div style="margin-top:26px;font-size:10.5px;color:#6b7280;line-height:1.6">
      ${tr(
        `Commission calculée à ${rateStr} du montant vendu sur la période. Montant dû ; le versement effectif au commercial est constaté séparément.`,
        `Commission computed at ${rateStr} of the amount sold over the period. Amount due; the actual payment to the salesperson is recorded separately.`,
      )}
    </div>
    <div style="margin-top:34px; display:flex; gap:60px; flex-wrap:wrap">
      <div style="flex:1; min-width:200px"><div class="party__label">${tr("La direction financière", "The finance department")}</div><div style="border-top:1px solid #16233d; margin-top:44px; padding-top:4px; font-size:10.5px; color:#6b7280">${tr("Signature &amp; cachet", "Signature &amp; stamp")}</div></div>
      <div style="flex:1; min-width:200px"><div class="party__label">${tr("Le commercial", "The salesperson")}</div><div style="border-top:1px solid #16233d; margin-top:44px; padding-top:4px; font-size:10.5px; color:#6b7280">${tr("Reçu — signature", "Received — signature")}</div></div>
    </div>`;

  openPrintWindow(`${tr("État de commission", "Commission statement")} — ${d.agentName}`, body, opts);
}

